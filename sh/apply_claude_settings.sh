#!/bin/bash
#
# Switch the active Claude Code config dir (account) for this machine.
#
# CLAUDE_CONFIG_DIR has to reach the VS Code Remote-SSH *server* process, because
# the extension host -- not the spawned CLI -- is what reads the session history,
# the ide/ lock dir, the file-history checkpoints and settings.json. The extension
# only injects `claudeCode.environmentVariables` into the CLI it spawns, so a
# settings.json-only switch leaves the sidebar reading ~/.claude.
#
# The server is started over ssh by a non-interactive bash, which still sources
# ~/.bashrc, so exporting there covers server -> extension host -> CLI -> terminal
# in one place. This script owns that single switch point; nothing else needs to
# carry the value.
#
# Profiles are discovered at runtime from $HOME/.claude-<profile> directories, so
# no account name, address or machine-specific path is baked into this file.

set -uo pipefail

ENV_FILE="$HOME/.claude-config-dir.env"
BASHRC="$HOME/.bashrc"

BEGIN_MARK="# >>> claude config dir (managed by apply_claude_settings.sh) >>>"
END_MARK="# <<< claude config dir (managed by apply_claude_settings.sh) <<<"

DRY_RUN=false
PROFILE=""

# Config dir for a profile name; "default" means the stock ~/.claude.
profile_dir() {
    if [ "$1" = "default" ]; then
        printf '%s\n' "$HOME/.claude"
    else
        printf '%s\n' "$HOME/.claude-$1"
    fi
}

# Profile names available on this machine, in directory order. A config dir is
# recognised by its own settings.json / .claude.json, which keeps sibling state
# dirs such as .claude-<profile>.lock out of the list.
list_profiles() {
    local d
    is_config_dir "$HOME/.claude" && printf '%s\n' "default"
    for d in "$HOME"/.claude-*; do
        is_config_dir "$d" || continue
        printf '%s\n' "${d##*/.claude-}"
    done
}

is_config_dir() {
    [ -d "$1" ] && { [ -e "$1/settings.json" ] || [ -e "$1/.claude.json" ]; }
}

# Account the given config dir is logged in as, read from its own .claude.json.
# Purely cosmetic -- stays quiet when the file, or a JSON reader, is missing.
profile_account() {
    local json="$1/.claude.json"
    [ -r "$json" ] || return 0
    if command -v jq >/dev/null 2>&1; then
        jq -r '.oauthAccount.emailAddress // empty' "$json" 2>/dev/null
    elif command -v python3 >/dev/null 2>&1; then
        python3 -c 'import json,sys
try:
    a = json.load(open(sys.argv[1])).get("oauthAccount") or {}
except Exception:
    raise SystemExit(0)
print(a.get("emailAddress") or "")' "$json" 2>/dev/null
    fi
}

usage() {
    local p dir account
    cat <<EOF
Usage: $0 <profile> [--dry-run]
  -n, --dry-run: Show what would change without touching any file

Profiles found on this machine (\$HOME/.claude-<profile>):
EOF
    while read -r p; do
        [ -n "$p" ] || continue
        dir=$(profile_dir "$p")
        account=$(profile_account "$dir")
        printf '  %-14s %s%s\n' "$p" "${dir/#"$HOME"/\~}" "${account:+  ($account)}"
    done < <(list_profiles)

    cat <<EOF

After switching, restart the VS Code server so the extension host picks up the
new value (a window reload is not enough -- the server is what holds the env):

  pkill -f '\.vscode-server/(code-[0-9a-f]{40}|cli/servers/[^ ]*/server/bin/code-server)'

then reconnect from the client.
EOF
}

for arg in "$@"; do
    case "$arg" in
        -n|--dry-run)
            DRY_RUN=true
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        -*)
            usage >&2
            exit 1
            ;;
        *)
            if [ -n "$PROFILE" ]; then
                usage >&2
                exit 1
            fi
            PROFILE="$arg"
            ;;
    esac
done

if [ -z "$PROFILE" ]; then
    usage >&2
    exit 1
fi

CLAUDE_DIR=$(profile_dir "$PROFILE")

if [ ! -d "$CLAUDE_DIR" ]; then
    echo "Warning: $CLAUDE_DIR does not exist yet; it will be created on first login." >&2
fi

failed=0

echo "Target config dir: $CLAUDE_DIR"
echo

# --- 1. The single switch point: a generated file sourced from ~/.bashrc -------

echo "Writing env file: $ENV_FILE"
if [ "$DRY_RUN" = false ]; then
    if ! cat > "$ENV_FILE" <<EOF
# Generated by apply_claude_settings.sh -- do not edit by hand.
# Sourced from ~/.bashrc before the non-interactive early return so that the
# VS Code Remote-SSH server (and its extension host) inherits the value.
export CLAUDE_CONFIG_DIR="$CLAUDE_DIR"
EOF
    then
        echo "Failed to write: $ENV_FILE" >&2
        failed=1
    fi
fi

# Reinstall the managed block at the top of ~/.bashrc. It must come before the
# `case $- in *i*) ;; *) return;; esac` guard, which would otherwise return
# before the export in the non-interactive server bootstrap.
echo "Installing managed block: $BASHRC"
if [ "$DRY_RUN" = false ]; then
    bashrc_tmp="${BASHRC}.tmp.$$"
    {
        printf '%s\n' "$BEGIN_MARK"
        printf '%s\n' 'if [ -r "$HOME/.claude-config-dir.env" ]; then'
        printf '%s\n' '    . "$HOME/.claude-config-dir.env"'
        printf '%s\n' 'fi'
        printf '%s\n' "$END_MARK"
        printf '\n'
        awk -v begin="$BEGIN_MARK" -v end="$END_MARK" '
            $0 == begin { skip = 1; next }
            $0 == end   { skip = 0; blank = 1; next }
            skip        { next }
            blank && $0 == "" { blank = 0; next }
            { blank = 0; print }
        ' "$BASHRC"
    } > "$bashrc_tmp"

    if bash -n "$bashrc_tmp" && cp --preserve=mode,ownership "$bashrc_tmp" "$BASHRC"; then
        rm -f "$bashrc_tmp"
    else
        rm -f "$bashrc_tmp"
        echo "Failed to update: $BASHRC" >&2
        failed=1
    fi
fi

# --- 2. Report ----------------------------------------------------------------

if [ "$failed" -ne 0 ]; then
    echo "Some files could not be updated." >&2
    exit 1
fi

if [ "$DRY_RUN" = true ]; then
    echo "Dry run completed. No files were changed."
    exit 0
fi

cat <<EOF
Done. CLAUDE_CONFIG_DIR=$CLAUDE_DIR

Restart the VS Code server so the extension host picks it up (a window reload is
not enough -- this drops the remote connection, so reconnect afterwards):

  pkill -f '\.vscode-server/(code-[0-9a-f]{40}|cli/servers/[^ ]*/server/bin/code-server)'

Verify after reconnecting:

  tr '\\0' '\\n' < /proc/\$(pgrep -f bootstrap-fork | head -1)/environ | grep CLAUDE_CONFIG_DIR
EOF
